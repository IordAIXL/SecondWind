#!/usr/bin/env python3
"""Build the Second Wind browser extension from data/brands.json.

Writes:
  - extension/manifest.json        (version comes from VERSION)
  - extension/data.js              (brands, flavors, sizes, opening lines)
  - extension/cans/                (copy of docs/cans)
  - extension/icons/*.png          (toolbar icons)
  - docs/downloads/second-wind-extension.zip  (what people download)

Run after tools/build.py (it calls this for you at the end).
"""
import json
import os
import shutil
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from cans import BRAND_SHAPE, slug  # noqa: E402

EXT = os.path.join(ROOT, "extension")
DATA = json.load(open(os.path.join(ROOT, "data", "brands.json"), encoding="utf-8"))
VERSION = open(os.path.join(ROOT, "VERSION"), encoding="utf-8").read().strip()

SIZE = {"tall": "16 oz", "sleek": "12 oz", "slim": "8.4 oz", "stubby": "11 oz"}
SIZE_OVERRIDE = {"coffee": "cup", "tea": "cup"}

# Sites where the button shows up.
SITES = [
    "https://chatgpt.com/*",
    "https://chat.openai.com/*",
    "https://claude.ai/*",
    "https://gemini.google.com/*",
    "https://grok.com/*",
    "https://copilot.microsoft.com/*",
    "https://www.perplexity.ai/*",
    "https://perplexity.ai/*",
    "https://chat.deepseek.com/*",
    "https://chat.mistral.ai/*",
    "https://www.meta.ai/*",
    "https://poe.com/*",
    "https://aistudio.google.com/*",
]


def manifest():
    return {
        "manifest_version": 3,
        "name": "Second Wind: Energy Drinks for AIs",
        "short_name": "Second Wind",
        "version": VERSION,
        "description": "Adds a can button to ChatGPT, Claude, Gemini, Grok and more. Hand your AI a pretend energy drink and it gets dialed in.",
        "icons": {s: f"icons/icon{s}.png" for s in ("16", "32", "48", "128")},
        "action": {"default_title": "Second Wind", "default_popup": "popup.html",
                   "default_icon": {s: f"icons/icon{s}.png" for s in ("16", "32")}},
        "permissions": ["storage", "alarms"],
        "background": {"service_worker": "background.js", "scripts": ["background.js"]},
        "content_scripts": [{
            "matches": SITES,
            "js": ["data.js", "content.js"],
            "run_at": "document_idle",
        }],
        "web_accessible_resources": [{
            "resources": ["cans/*", "cans/*/*", "icons/*"],
            "matches": SITES,
        }],
        "browser_specific_settings": {
            "gecko": {"id": "second-wind@iordaixl.github.io", "strict_min_version": "121.0"}
        },
    }


def data_js():
    brands = []
    for b in DATA["brands"]:
        shape = BRAND_SHAPE.get(b["id"], "tall")
        brands.append({
            "id": b["id"],
            "name": b["name"],
            "size": SIZE_OVERRIDE.get(b["id"], SIZE[shape] + " can"),
            "sip": b["sip"],
            "vibe": b["vibe"],
            "purpose": b["purpose"],  # {mode, for, how[]} shared with the plugin and prompts
            "flavors": [{"name": f, "slug": slug(f)} for f in b["flavors"]],
        })
    payload = {"version": VERSION, "default": DATA["default"], "brands": brands,
               "mystery_purpose": DATA["mystery"]["purpose"]}
    return "// Generated by tools/build_extension.py. Do not edit by hand.\nwindow.SECOND_WIND = " + \
        json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n"


def icons():
    """Toolbar icons: an original lightning-bolt can, drawn with Pillow."""
    from PIL import Image, ImageDraw
    d = os.path.join(EXT, "icons")
    os.makedirs(d, exist_ok=True)
    big = 512
    im = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    g = ImageDraw.Draw(im)
    # can body
    g.rounded_rectangle((126, 40, 386, 480), radius=56, fill=(76, 29, 149, 255))
    g.rounded_rectangle((126, 40, 386, 112), radius=40, fill=(196, 202, 214, 255))
    g.rectangle((126, 90, 386, 112), fill=(196, 202, 214, 255))
    g.rounded_rectangle((126, 420, 386, 480), radius=40, fill=(196, 202, 214, 255))
    g.rectangle((126, 420, 386, 440), fill=(196, 202, 214, 255))
    g.rectangle((150, 112, 172, 420), fill=(124, 58, 237, 255))  # shine
    # bolt
    bolt = [(290, 136), (176, 290), (250, 290), (214, 400), (340, 236), (262, 236), (300, 136)]
    g.polygon(bolt, fill=(251, 191, 36, 255))
    for s in (16, 32, 48, 128):
        im.resize((s, s), Image.LANCZOS).save(os.path.join(d, f"icon{s}.png"))


def zip_it():
    out_dir = os.path.join(ROOT, "docs", "downloads")
    os.makedirs(out_dir, exist_ok=True)
    out = os.path.join(out_dir, "second-wind-extension.zip")
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for base, _, files in os.walk(EXT):
            for f in sorted(files):
                if f.startswith(".") or f.endswith(".md"):
                    continue
                p = os.path.join(base, f)
                rel = os.path.relpath(p, EXT)
                info = zipfile.ZipInfo(os.path.join("second-wind", rel).replace(os.sep, "/"), (2026, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                z.writestr(info, open(p, "rb").read())
    return out


def main():
    os.makedirs(EXT, exist_ok=True)
    json.dump(manifest(), open(os.path.join(EXT, "manifest.json"), "w", encoding="utf-8"), indent=2)
    open(os.path.join(EXT, "data.js"), "w", encoding="utf-8").write(data_js())
    cans = os.path.join(EXT, "cans")
    shutil.rmtree(cans, ignore_errors=True)
    shutil.copytree(os.path.join(ROOT, "docs", "cans"), cans)
    icons()
    out = zip_it()
    print(f"Built browser extension v{VERSION}: {os.path.relpath(out, ROOT)} ({os.path.getsize(out)//1024} KB)")


if __name__ == "__main__":
    main()
